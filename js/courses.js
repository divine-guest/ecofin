/* Прогресс курсов: pf_course_<email> = { fin: [0,2], ... } — индексы пройденных уроков */
const COURSE_PROGRESS = {
  key() { const u = PF.user(); return "pf_course_" + (u ? u.email : "guest"); },
  get() { return JSON.parse(localStorage.getItem(this.key()) || "{}"); },
  done(courseId, lessonIdx) {
    const p = this.get();
    p[courseId] = [...new Set([...(p[courseId] || []), lessonIdx])];
    localStorage.setItem(this.key(), JSON.stringify(p));
  },
  reset(courseId) {
    const p = this.get();
    delete p[courseId];
    localStorage.setItem(this.key(), JSON.stringify(p));
  },
};
