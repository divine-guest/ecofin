/* Перемешивает варианты и помечает правильный. Общая функция для всех
   режимов: расположение ответа не должно ничего подсказывать. */
function shuffleAnswers(opts, correct) {
  const pairs = opts.map((text, i) => ({ text, right: i === correct }));
  for (let i = pairs.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pairs[i], pairs[j]] = [pairs[j], pairs[i]];
  }
  return pairs;
}

