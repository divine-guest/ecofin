/* Выжимка ставок для подсказки ИИ-консультанта.

   ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ.

   В подсказке стояло правило: «твои знания могут отставать от изменений
   законодательства, добавляй в конце — проверьте актуальную редакцию».
   Правило честное и совершенно бесполезное: модель всё равно называет
   число, а человек всё равно его записывает. Приписка снизу не отменяет
   цифру сверху.

   Проверено на живых вопросах 09.09.2026. Лимит УСН модель назвала
   277,4 млн вместо 450 млн. Ключевую ставку — 16% вместо 14%, и тут же
   посчитала по ней компенсацию за задержку зарплаты. Оба ответа
   выглядели уверенно, со ссылками на статьи и с вежливым советом
   свериться.

   При этом выверенные значения у нас есть: js/rates.js, полторы сотни
   проверок, дата сверки в самом файле. Модель их просто не видела.

   ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧТЕНИЕ НА ЛЕТУ.

   js/rates.js написан для браузера: объявляет const и ничего не
   экспортирует. Тесты выполняют его через new Function, но на
   Cloudflare Workers это запрещено. Поэтому выжимка собирается заранее
   и кладётся обычным модулем, который импортируется откуда угодно.

   Расхождение стережёт проверка в tests/content.mjs: она собирает
   выжимку заново и сравнивает с лежащей в репозитории. Забыть
   пересобрать нельзя — упадёт.

   Запуск: node scripts/make-rates-digest.mjs                          */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

const rub = n => Number(n).toLocaleString("ru-RU");
const pct = n => `${+(Number(n) * 100).toFixed(2)}%`;
const mln = n => `${Number(n) / 1e6} млн`;

export function buildDigest(src) {
  const { RATES: R } = new Function(src + "\nreturn { RATES };")();
  const L = [];

  L.push(`ВЫВЕРЕННЫЕ ЗНАЧЕНИЯ СЕРВИСА НА ${R.year} ГОД (сверены ${R.checkedOn}).`);
  L.push(`Это те же числа, по которым считают калькуляторы сайта. Если твои знания расходятся с ними — верны эти, и приписку «проверьте актуальность» к ним добавлять не нужно.`);
  L.push("");

  L.push(`Ключевая ставка ЦБ: ${R.keyRate.percent}% (сверена ${R.keyRate.checkedOn}). По ней считаются пеня по налогам, проценты по ст. 395 ГК и компенсация за задержку зарплаты по ст. 236 ТК (1/150 ставки за каждый день).`);
  L.push(`МРОТ: ${rub(R.sickLeave.minWageMonth)} ₽ в месяц.`);
  L.push("");

  L.push(`ИП «за себя»: фиксированные взносы ${rub(R.ipContributions.fixed)} ₽ за полный год; с дохода сверх ${rub(R.ipContributions.extraThreshold)} ₽ — ещё ${pct(R.ipContributions.extraRate)}, но не более ${rub(R.ipContributions.extraCap)} ₽.`);
  L.push("");

  L.push(`УСН: лимит дохода ${mln(R.usn.limit)} ₽; «Доходы» ${pct(R.usn.incomeRate)}, «Доходы минус расходы» ${pct(R.usn.profitRate)}, минимальный налог ${pct(R.usn.minTaxRate)} от дохода.`);
  L.push(`НДС на УСН начинается с выручки ${mln(R.usn.vatThreshold)} ₽. Ставки НДС: ${R.vatRates.map(v => v.label).join("; ")}.`);
  L.push(`НПД: лимит ${mln(R.npd.limit)} ₽ в год, ${pct(R.npd.ratePersons)} с доходов от физлиц и ${pct(R.npd.rateCompanies)} — от юрлиц и ИП.`);
  L.push(`ПСН: ${pct(R.psn.rate)}, лимит дохода ${mln(R.psn.incomeLimit)} ₽, до ${R.psn.workersLimit} работников.`);
  L.push(`АУСН: «Доходы» ${pct(R.ausn.incomeRate)}, «Доходы минус расходы» ${pct(R.ausn.profitRate)}, минимальный ${pct(R.ausn.minTaxRate)}; лимит ${mln(R.ausn.incomeLimit)} ₽, до ${R.ausn.workersLimit} работников; взносы заменены фиксированным взносом на травматизм ${rub(R.ausn.injuryFixed)} ₽.`);
  /* Освобождение от НДС на ЕСХН с 2026 года не автоматическое.
     Число прежнее, поведение противоположное: кто не подал
     уведомление, тот стал плательщиком НДС, не заметив этого.
     Модель обязана сказать об этом, а не только назвать порог. */
  L.push(`ЕСХН: ${pct(R.eshn.rate)}; освобождение от НДС при доходе до ${mln(R.eshn.vatExemptUpTo)} ₽, но с 2026 года ТОЛЬКО ПО УВЕДОМЛЕНИЮ по ст. 145 НК — автоматически оно больше не даётся.`);
  L.push(`ОСНО: налог на прибыль ${pct(R.osno.profitTaxRate)}; профвычет ИП без подтверждённых расходов ${pct(R.osno.proDeduction)}.`);
  L.push("");

  /* Верхняя ступень задана Infinity, а не null: JSON.stringify
     превращает её в null и на этом легко обмануться. Проверяем
     конечность, иначе в подсказку уезжает «22% до ∞ ₽». */
  L.push(`НДФЛ, пятиступенчатая шкала: ${R.ndflScale.map(s => Number.isFinite(s.upTo) ? `${pct(s.rate)} до ${rub(s.upTo)} ₽` : `${pct(s.rate)} свыше ${rub(R.ndflScale[R.ndflScale.length - 2].upTo)} ₽`).join("; ")}.`);
  L.push(`Взносы за работников: предельная база ${rub(R.payrollContrib.base)} ₽, тариф ${pct(R.payrollContrib.rate)}, свыше базы ${pct(R.payrollContrib.rateOverBase)}; для МСП с части свыше МРОТ ${pct(R.payrollContrib.smallRateOverMrot)}.`);
  L.push(`Больничный: предельные базы за ${R.sickLeave.baseYears.join(" и ")} годы — ${R.sickLeave.bases.map(rub).join(" и ")} ₽; расчётный период ${R.sickLeave.days} дней.`);
  L.push("");

  /* Правила расчёта, а не только числа.

     Выяснилось на проверке: выверенные ставки решают только половину
     задачи. Три разные модели, получив верные 57 390, 29 000 и 192 000,
     назвали итог 232 500, 347 390 и 430 438 ₽ вместо 192 000. Слагаемые
     верные, сумма — нет.

     Причина одна и та же: модель не применяет правило вычета. ИП без
     работников уменьшает налог на взносы полностью, и тогда «взносы
     плюс налог» равны самому налогу. Это не арифметика, это норма,
     и её надо назвать прямо. */
  L.push("");
  L.push(`ПРАВИЛА РАСЧЁТА, которые чаще всего применяют неверно:`);
  L.push(`1. ИП на УСН «Доходы» БЕЗ работников уменьшает налог на страховые взносы за себя ПОЛНОСТЬЮ, вплоть до нуля (п. 3.1 ст. 346.21 НК РФ). Поэтому «взносы плюс налог» у такого ИП равны сумме налога до вычета: если налог ${pct(R.usn.incomeRate)} составил X, а взносы Y, то к уплате налога X−Y, а всего отдано X, а не X+Y.`);
  L.push(`2. ИП и организации С работниками уменьшают налог на УСН «Доходы» не более чем наполовину.`);
  L.push(`3. Взносы за себя уменьшают налог того года, за который они начислены, независимо от даты фактической уплаты.`);
  L.push(`4. На УСН «Доходы минус расходы» взносы не вычитаются из налога — они входят в расходы.`);
  L.push(`5. Компенсация по ст. 236 ТК: сумма долга × ключевая ставка / 150 × дни. Ставка берётся как доля, не как проценты: 14% — это 0,14.`);
  L.push("");
  L.push(`ПЕРЕД ТЕМ КАК НАЗВАТЬ ИТОГ, ПРОВЕРЬ ЕГО: сложи слагаемые заново и убедись, что вывод совпадает с разбором. Расхождение между суммой в выводе и числами в шагах — самая частая и самая дорогая ошибка: человек читает только вывод.`);
  L.push("");
  L.push(`Если нужного значения здесь нет — не называй его по памяти: скажи, где свериться (сайт ФНС, КонсультантПлюс), или предложи калькулятор сервиса.`);

  return L.join("\n");
}

export const HEADER = `/* СОБРАНО АВТОМАТИЧЕСКИ — руками не править.

   Источник: js/rates.js. Пересобрать: node scripts/make-rates-digest.mjs

   Зачем. В подсказке консультанта стояло «твои знания могут отставать,
   добавляй приписку проверить актуальность». Приписка снизу не отменяет
   цифру сверху: на живых вопросах модель называла лимит УСН 277,4 млн
   вместо 450 млн и ключевую ставку 16% вместо 14% — и тут же вежливо
   советовала свериться.

   Теперь выверенные значения едут вместе с вопросом. Расхождение с
   js/rates.js ловит проверка в tests/content.mjs.                    */

`;

export function digestModule(src) {
  return HEADER + `export const RATES_DIGEST = ${JSON.stringify(buildDigest(src))};\n`;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  const src = readFileSync(join(ROOT, "js", "rates.js"), "utf8");
  const digest = buildDigest(src);
  writeFileSync(join(ROOT, "worker", "src", "rates-digest.js"), digestModule(src), "utf8");
  console.log("выжимка собрана,", digest.length, "символов\n");
  console.log(digest);
}
