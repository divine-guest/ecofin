/* Обезличивание перед отправкой за границу.

   Что здесь на кону. Вычисления языковой модели идут за пределами
   России. Пока в тексте есть данные, по которым можно определить
   человека, это трансграничная передача персональных данных со всеми
   обязанностями и штрафами. После замены передавать нечего.

   Ошибка тут двусторонняя и обе дорогие:
     — пропустили опознаватель — он уехал за границу;
     — замаскировали лишнее — инструмент отвечает бессмыслицу
       («правильный ли у вас [СЧЁТ-1]») и перестаёт быть нужным.

   Проверка офлайн: redact — чистая функция.                        */

import fs from "node:fs";
import { redact, restore, redactOn } from "../worker/src/redact.js";

let pass = 0, fail = 0;
const ok = (c, label, got = "") => {
  c ? (pass++, console.log("  ✓", label)) : (fail++, console.log("  ✗", label, "→", JSON.stringify(got)));
};
const hidden = t => redact(t).text;

console.log("\n— Опознаватели человека не уходят —");
{
  ok(!hidden("ИНН 262300558403").includes("262300558403"), "ИНН физлица (12 цифр)");
  ok(!hidden("ИНН 7707083893").includes("7707083893"), "ИНН организации (10 цифр)");
  ok(!hidden("ОГРНИП 324265100146987").includes("324265100146987"), "ОГРНИП (15 цифр)");
  ok(!hidden("ОГРН 1027700132195").includes("1027700132195"), "ОГРН (13 цифр)");
  ok(!hidden("СНИЛС 112-233-445 95").includes("112-233-445"), "СНИЛС");
  ok(!hidden("паспорт 07 05 123456").includes("123456"), "паспорт");
  ok(!hidden("счёт 40802810100000012345").includes("40802810100000012345"), "номер счёта");
  ok(!hidden("карта 4276 3800 1234 5678").includes("4276"), "номер карты");
  ok(!hidden("телефон +7 (918) 123-45-67").includes("123-45-67"), "телефон с кодом +7");
  ok(!hidden("звоните 8 918 123 45 67").includes("918"), "телефон с восьмёрки");
  ok(!hidden("почта ivanov@mail.ru").includes("ivanov@mail.ru"), "адрес почты");
}

console.log("\n— Имена: главная ловушка кириллицы —");
{
  /* В JavaScript \b определяется через \w, а \w — только латиница.
     Правила с \b перед кириллической буквой не срабатывают ВООБЩЕ и
     делают это молча: числовые правила рядом работают, и защита
     выглядит живой. Имена не маскировались ни разу. */
  ok(!hidden("Иванов Иван Иванович").includes("Иванов"), "ФИО в именительном падеже");
  ok(!hidden("Договор с Ивановым Иваном Ивановичем").includes("Ивановым"),
     "ФИО в творительном падеже", hidden("Договор с Ивановым Иваном Ивановичем"));
  ok(!hidden("Сидорова Анна Сергеевна").includes("Сидорова"), "женское ФИО");
  ok(!hidden("Подписал Петров П. П.").includes("Петров"),
     "фамилия с инициалами после", hidden("Подписал Петров П. П."));
  ok(!hidden("П. П. Петров подписал").includes("Петров"),
     "инициалы перед фамилией", hidden("П. П. Петров подписал"));

  /* Одно значение — одна метка: иначе модель решит, что в договоре
     два разных человека с одним ИНН. */
  const r = redact("ИНН 262300558403 и ещё раз ИНН 262300558403");
  ok((r.text.match(/\[ИНН-1\]/g) || []).length === 2, "повтор получает ту же метку", r.text);
  ok(r.count === 1, "в словаре одна запись, а не две", r.count);
}

console.log("\n— Смысл вопроса не ломается —");
{
  /* Замаскировать КБК значит превратить ответ про платёжку в
     бессмыслицу. А «Заявление об уточнении платежа» — один из самых
     нужных документов: ошиблись в КБК, деньги ушли, долг остался. */
  const kbk = "Ошибся в КБК 18210501011011000110 при уплате УСН";
  ok(kbk === hidden(kbk), "КБК остаётся на месте", hidden(kbk));
  ok(hidden("УИН 18209965240000012345").includes("18209965240000012345"), "УИН остаётся");
  ok(hidden("ОКТМО 45382000").includes("45382000"), "ОКТМО остаётся");
  ok(hidden("БИК 044525225").includes("044525225"), "БИК остаётся");

  /* Ссылки на нормы, суммы и даты — это содержание вопроса. */
  const law = "Основание — п. 3 ст. 88 НК РФ и 152-ФЗ";
  ok(law === hidden(law), "ссылки на статьи целы", hidden(law));
  ok(hidden("сумма 1250000 рублей").includes("1250000"), "суммы целы");
  ok(hidden("за 2025 год").includes("2025"), "годы целы");
  ok(hidden("с 01.09.2026").includes("01.09.2026"), "даты целы");

  /* Три слова с заглавной — не обязательно имя. */
  const code = "Налоговый Кодекс Российской Федерации";
  ok(code === hidden(code), "название закона не принято за ФИО", hidden(code));
  const org = "ООО «Ромашка» и ИП Сидоров";
  ok(org === hidden(org), "названия организаций целы", hidden(org));
}

console.log("\n— Ответ возвращается человеку читаемым —");
{
  const r = redact("Договор с Ивановым И. И., ИНН 262300558403");
  const answer = `По договору ${[...r.map.keys()].join(" и ")} должен уплатить.`;
  const back = restore(answer, r.map);
  ok(back.includes("Ивановым И. И."), "имя вернулось", back);
  ok(back.includes("262300558403"), "ИНН вернулся", back);
  ok(!/\[[А-ЯЁ]+-\d\]/.test(back), "меток в ответе не осталось", back);

  ok(restore("обычный ответ", new Map()) === "обычный ответ", "ответ без меток не портится");
  ok(restore("", r.map) === "", "пустой ответ не роняет");
}

console.log("\n— Крайние случаи —");
{
  ok(redact("").count === 0, "пустой текст");
  ok(redact(null).text === "", "отсутствующий текст не роняет");
  ok(redact(undefined).count === 0, "undefined не роняет");

  /* Выключатель нужен, чтобы отключить правило мгновенно, если оно
     однажды начнёт портить вопросы. */
  ok(redactOn({}) === true, "по умолчанию обезличивание включено");
  ok(redactOn({ REDACT_PII: "0" }) === false, "выключается переменной");
  ok(redactOn({ REDACT_PII: "1" }) === true, "включается обратно");
}

console.log("\n— Настоящий документ целиком —");
{
  const doc = `ДОГОВОР ОКАЗАНИЯ УСЛУГ № 14 от 01.09.2026

Исполнитель: ИП Калайтанов Пётр Сергеевич, ИНН 262300558403,
ОГРНИП 324265100146987, счёт 40802810100000012345, тел. +7 918 123-45-67.

Заказчик: ООО «Вектор», ИНН 7707083893, в лице директора Смирнова А. В.

1. Стоимость услуг 250 000 рублей, оплата до 15.10.2026.
2. При просрочке — пеня 0,1% за каждый день (ст. 330 ГК РФ).
3. КБК для уплаты налога 18210501011011000110.`;

  const r = redact(doc);
  const out = r.text;

  for (const secret of ["262300558403", "324265100146987", "40802810100000012345",
                        "918 123-45-67", "Калайтанов", "Смирнова А. В.", "7707083893"]) {
    ok(!out.includes(secret), `не уходит: ${secret}`);
  }
  for (const keep of ["250 000", "15.10.2026", "ст. 330 ГК РФ", "0,1%",
                      "ООО «Вектор»", "18210501011011000110", "№ 14"]) {
    ok(out.includes(keep), `остаётся: ${keep}`);
  }
  ok(r.count >= 6, `замен в документе: ${r.count}`, r.count);
}

console.log("\n— Мимо обезличивания пройти нельзя —");
{
  /* Как это сломалось в первый раз.

     Обезличивание сделали в ai.js и проверили: на сайте вопрос уходит
     метками вместо имён и счетов. А в telegram.js лежала копия кода —
     свой запрос к поставщику, написанный когда-то ради скорости. Тот
     же вопрос, заданный в мессенджере, уходил за границу как есть.
     Полгода. При этом политика обещала обезличивание всем.

     Копия кода не отстаёт от оригинала постепенно. Она отстаёт сразу
     и молча — при первой же правке оригинала, и заметить это по
     работе сервиса невозможно: оба пути отвечают одинаково хорошо.

     Поэтому проверяется не «обезличивание работает», а «второго пути
     наружу не существует». */

  const dir = new URL("../worker/src/", import.meta.url);
  const files = fs.readdirSync(dir).filter(f => f.endsWith(".js"));

  const callers = files.filter(f =>
    /chat\/completions/.test(fs.readFileSync(new URL(f, dir), "utf8")));
  ok(callers.length === 1 && callers[0] === "ai.js",
     "адрес поставщика назван ровно в одном модуле", callers);

  /* Кто отправляет текст человека — обязан сначала его спрятать. */
  const tg = fs.readFileSync(new URL("telegram.js", dir), "utf8");
  ok(/callProvider/.test(tg), "бот спрашивает модель общим вызовом, а не своим");
  ok(/redactOn\(env\) \? redact\(text\)/.test(tg), "и обезличивает вопрос перед отправкой");
  ok(/restore\(answer, hide\.map\)/.test(tg), "а метки в ответе разворачивает обратно");

  const ai = fs.readFileSync(new URL("ai.js", dir), "utf8");
  ok(/redactOn\(env\) \? redact\(/.test(ai), "сайт обезличивает так же");

  /* Обещание в политике и поведение кода должны совпадать: расхождение
     здесь — это не ошибка вёрстки, а неверное утверждение в
     опубликованном документе. */
  const legal = fs.readFileSync(new URL("../legal.html", import.meta.url), "utf8");
  /* [а-яё], а не \w: в JavaScript \w — только латиница, и правило с
     ним по-русски молча не срабатывает. Ровно на этом однажды
     сломалось само обезличивание ФИО. */
  ok(/обезличенн[а-яё]* текст обращения/.test(legal),
     "политика обещает обезличивание — и теперь это верно для всех путей");
}

console.log("\n— Снимки не уходят за границу вообще —");
{
  /* Раньше здесь стоял запасной путь: если нет ни ключа Yandex Vision,
     ни tesseract — снимок уходил в зарубежную зрячую модель. Сработать
     он мог только на машине без tesseract, а на боевой он стоит, то
     есть в жизни путь не срабатывал никогда.

     Убрали его не поэтому. Политика обещает не «обычно не передаём», а
     «изображения за пределы Российской Федерации не передаются», и то
     же самое идёт в уведомление в Роскомнадзор. Обещание, у которого
     в коде есть исключение, — это неверное утверждение в документе,
     поданном в госорган.

     Плюс цена вопроса: зрячая модель — это США, а США в перечень
     государств с адекватной защитой не входят (приказ Роскомнадзора
     № 128). Один неиспользуемый путь потянул бы всё уведомление
     в более тяжёлый режим ради возможности, которой никто не
     пользовался. */

  const src = new URL("../worker/src/", import.meta.url);
  const files = fs.readdirSync(src).filter(f => f.endsWith(".js"));

  /* Картинку модели можно отправить единственным способом — полем
     image_url в сообщении. Его не должно быть нигде. */
  const senders = files.filter(f => /image_url/.test(fs.readFileSync(new URL(f, src), "utf8")));
  ok(senders.length === 0, "ни один модуль не отправляет изображение модели", senders);

  /* Модель для картинок больше не настраивается: настройка, которой
     нечем воспользоваться, однажды снова обзаведётся кодом. */
  const usesVisionModel = files.filter(f => /AI_VISION_MODEL/.test(fs.readFileSync(new URL(f, src), "utf8")));
  ok(usesVisionModel.length === 0, "настройки зарубежной зрячей модели не осталось", usesVisionModel);

  const vision = fs.readFileSync(new URL("vision.js", src), "utf8");
  ok(/ocrReady\(env\)/.test(vision) && /localOcrReady\(\)/.test(vision),
     "остались два пути распознавания, оба внутри страны");
  ok(!/callProvider\(env/.test(vision),
     "vision.js больше не обращается к поставщику модели");

  /* Не получилось внутри страны — честный отказ, а не тихая отправка. */
  ok(/throw new Error\([\s\S]{0,200}только[\s\S]{0,60}России/.test(vision),
     "при неудаче человеку объясняют причину, а снимок никуда не едет");

  /* И политика по-прежнему обещает ровно это. */
  const legal = fs.readFileSync(new URL("../legal.html", import.meta.url), "utf8");
  ok(/за пределы Российской[\s]+Федерации не передаются/.test(legal),
     "политика обещает то же, что делает код");
}

console.log(`\nИТОГО: ${pass} пройдено, ${fail} провалено\n`);
process.exit(fail ? 1 : 0);
