/* Чистка markdown из ответов ИИ.

   Проверка нужна не столько на «убирает звёздочки», сколько на
   «не трогает чужое». Функция работает над текстом, который человек
   потом распечатает и отнесёт в банк или налоговую: одна лишняя правка
   в номере карты или в сумме — и документ испорчен молча. */
import fs from "node:fs";

const src = fs.readFileSync(new URL("../js/app.js", import.meta.url), "utf8");
const m = src.match(/function plainText\(s\) \{[\s\S]*?\n\}/);
if (!m) { console.log("не найдена функция plainText"); process.exit(1); }
eval(m[0] + "\nglobalThis.plainText = plainText;");
const P = globalThis.plainText;

let pass = 0, fail = 0;
const ok = (c, label, got = "") => {
  c ? (pass++, console.log("  ✓", label)) : (fail++, console.log("  ✗", label, "→", JSON.stringify(got)));
};
const eq = (input, want, label) => {
  const got = P(input);
  ok(got === want, label, got);
};

console.log("\n— Убирает выделение —");
eq("**Итого:** 45 000 ₽", "Итого: 45 000 ₽", "двойные звёздочки");
eq("***Очень важно***", "Очень важно", "тройные звёздочки");
eq("Ставка *шесть* процентов", "Ставка шесть процентов", "одинарные звёздочки");
eq("__Подчёркнутый__", "Подчёркнутый", "двойное подчёркивание");
eq("Текст с `кодом` внутри", "Текст с кодом внутри", "обратные кавычки");
eq("```\nстрока\n```", "строка", "блок кода");

console.log("\n— Не ломает чужое —");
eq("Карта **** 1234", "Карта **** 1234", "маскированный номер карты");
eq("Счёт **** **** **** 5678", "Счёт **** **** **** 5678", "номер из четырёх групп");
eq("Пароль скрыт: ******", "Пароль скрыт: ******", "строка звёздочек");
eq("Остаток -5 000 ₽", "Остаток -5 000 ₽", "отрицательная сумма не стала списком");
eq("Сноска * к таблице", "Сноска * к таблице", "одинокая звёздочка в предложении");
eq("2 * 2 = 4", "2 * 2 = 4", "знак умножения");
eq("--- страница 2 ---", "--- страница 2 ---", "наш разделитель страниц из распознавания");
eq("файл_с_подчёркиваниями_v2", "файл_с_подчёркиваниями_v2", "подчёркивания внутри слова");

console.log("\n— Заголовки и списки —");
eq("### Итого", "ИТОГО", "решётки становятся заглавными");
eq("## Раздел 1 ##", "РАЗДЕЛ 1", "закрывающие решётки тоже убираются");
eq("* первый\n* второй", "— первый\n— второй", "маркеры списка становятся тире");
eq("- пункт", "— пункт", "дефис-маркер тоже");
eq("1. первый\n2. второй", "1. первый\n2. второй", "нумерованный список не трогаем");

console.log("\n— Разделители —");
eq("Текст\n\n***\n\nЕщё", "Текст\n\nЕщё", "линия из звёздочек убрана");
eq("Текст\n\n---\n\nЕщё", "Текст\n\nЕщё", "линия из дефисов убрана");

console.log("\n— Ссылки и цитаты —");
eq("[ФНС](https://nalog.gov.ru)", "ФНС (https://nalog.gov.ru)", "адрес сохраняется");
eq("> цитата", "цитата", "знак цитаты убран");

console.log("\n— Таблицы —");
eq("| Налог | Сумма |\n|---|---|\n| УСН | 6000 |",
   "Налог · Сумма\nУСН · 6000", "таблица превращается в строки");

console.log("\n— Пустые значения —");
eq("", "", "пустая строка");
ok(P(null) === "", "null не роняет");
ok(P(undefined) === "", "undefined не роняет");

console.log("\n— Живой пример ответа —");
{
  const raw = `### Расчёт налога

**Итого к уплате:** 45 000 ₽

* УСН 6% — 30 000 ₽
* Взносы — 15 000 ₽

---

Проверьте актуальную редакцию.`;
  const got = P(raw);
  ok(!got.includes("*"), "ни одной звёздочки не осталось", got);
  ok(!got.includes("#"), "ни одной решётки не осталось", got);
  ok(got.includes("РАСЧЁТ НАЛОГА"), "заголовок стал заглавным", got);
  ok(got.includes("45 000 ₽"), "сумма на месте", got);
  ok(got.includes("— УСН 6% — 30 000 ₽"), "пункт списка оформлен тире", got);
}

console.log(`\nИТОГО: ${pass} пройдено, ${fail} провалено`);
process.exit(fail ? 1 : 0);
