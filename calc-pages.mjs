const NB = " ";
const num = (n, digits = 0) => Number(n).toLocaleString("ru-RU",
  { minimumFractionDigits: digits, maximumFractionDigits: digits });
const rub = n => `${num(Math.round(n))}${NB}₽`;
const kop = n => `${num(n, 2)}${NB}₽`;
const pct = x => {
  const v = +(x * 100).toFixed(2);
  return `${num(v, (String(v).split(".")[1] || "").length)}%`;
};
const mln = n => {
  const v = n / 1e6;
  return `${num(v, v % 1 ? 1 : 0)}${NB}млн${NB}₽`;
};
const comma = x => String(x).replace(".", ",");

