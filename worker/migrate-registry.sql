-- Кэш ответов государственных реестров.
--
-- Обращения идут к чужому серверу: он может отвечать медленно, а может
-- ограничивать частоту. Повторный вопрос про тот же ИНН в тот же день
-- не должен уходить наружу второй раз — ни ради скорости, ни ради того,
-- чтобы нас не приняли за робота.
--
-- Персональных данных здесь нет: это сведения из открытых реестров,
-- которые ФНС публикует именно для проверки контрагентов.

CREATE TABLE IF NOT EXISTS registry_cache (
  k       TEXT PRIMARY KEY,   -- вида 'npd:ИНН:дата' или 'egr:ИНН'
  payload TEXT NOT NULL,      -- готовый ответ в JSON
  at      INTEGER NOT NULL    -- когда положили, unix ms
);

CREATE INDEX IF NOT EXISTS idx_registry_at ON registry_cache (at);
