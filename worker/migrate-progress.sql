-- Прогресс, который раньше жил только в браузере: «Копилка», уроки курсов,
-- результаты практикума, дневник трат, прочитанные статьи, ответы онбординга.
--
-- Зачем: страница входа обещает «прогресс будет на месте» на любом
-- устройстве. Для подписки и расчётов это было правдой, для серии дней
-- и курсов — нет. Серия дней — главный ежедневный крючок сервиса,
-- и она обнулялась при переходе с телефона на компьютер.
--
-- Одна таблица «ключ → данные» вместо пяти отдельных: смысл везде один,
-- а слияние делает клиент по правилу «данные только прибавляются».

CREATE TABLE IF NOT EXISTS progress (
  email      TEXT NOT NULL,
  key        TEXT NOT NULL,     -- habits | courses | scores | read | expenses | prefs
  data       TEXT NOT NULL,     -- JSON
  updated_at INTEGER NOT NULL,
  PRIMARY KEY (email, key)
);

CREATE INDEX IF NOT EXISTS idx_progress_email ON progress(email);
