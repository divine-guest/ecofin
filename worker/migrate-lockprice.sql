-- Цена, зафиксированная за подписчиком.
--
-- На витрине обещано: «пока подписка активна, вы платите столько же,
-- сколько при оформлении, даже если тарифы вырастут». Код обещание не
-- держал: автопродление брало текущую цену из plans.js, и после
-- повышения человек заплатил бы больше, ничего не подписывая заново.
--
-- Храним сумму в рублях за период, по которому оформлена подписка
-- (auto_plan хранит «basic:month» — период там же). Ноль и NULL
-- означают «фиксации нет, берём текущую цену».
--
-- Если цена СНИЗИТСЯ, зафиксированная не применяется: списываем
-- меньшую из двух. Обещание защищает от подорожания, а не мешает
-- человеку получить выгоду.
ALTER TABLE users ADD COLUMN auto_price REAL DEFAULT 0;
