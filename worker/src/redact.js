/* ============ ЭкоФин — обезличивание перед отправкой ============

   Зачем это здесь.

   Текст вопроса уходит языковой модели, вычисления которой идут за
   пределами России. Пока в тексте есть данные, по которым можно
   определить человека, это трансграничная передача персональных
   данных со всеми вытекающими обязанностями. Как только таких данных
   в тексте нет — передавать нечего: обезличенные сведения
   персональными данными не являются.

   Поэтому маскируем у себя, на сервере в России, ДО отправки.
   Поставщик тоже предлагает такую услугу, но полагаться на чужую
   настройку в чужой панели нельзя: она может быть выключена, и узнать
   об этом мы не сможем никак.

   Что делаем и чего не делаем.

   Маскируются опознаватели: ИНН, СНИЛС, паспорт, ОГРН, номера счетов
   и карт, телефоны, почта, ФИО. Каждый заменяется меткой вида
   [ФИО-1], а не вырезается: модель должна понимать, что здесь было
   имя, и рассуждать про «первую сторону». В ответе метки заменяются
   обратно, поэтому человек получает нормальный текст.

   НЕ маскируются суммы, даты, названия организаций и предмет
   договора: без них ответ бессмыслен, а персональными данными они
   сами по себе не являются.

   Важное ограничение, которое надо понимать честно: полного
   обезличивания текстовым разбором не добиться. Человек может
   описать себя словами, по которым он узнаваем, и никакое правило
   этого не поймает. Поэтому маскирование — мера снижения, а не
   основание считать, что персональных данных в запросе нет
   гарантированно.                                                  */

/* Порядок важен: длинные и однозначные образцы идут первыми, иначе
   короткое правило откусит кусок от длинного. Например, номер счёта
   из двадцати цифр не должен распасться на «ИНН + остаток». */
const RULES = [
  /* --- Однозначные по формату --- */

  /* Двадцать цифр — это и номер счёта, и КБК, и УИН. Первое стоит
     маскировать, второе и третье — нет: это коды вида платежа, а не
     человека, и без них ответ про платёжку бессмыслен. Смотрим, что
     написано перед числом. */
  { tag: "СЧЁТ", re: /\b\d{20}\b/g,
    skipNear: /(КБК|УИН|уникальн\w* идентификатор|код\w* бюджетн\w*)[^\d]{0,20}$/i },

  /* Карта: 16 цифр подряд или группами по четыре. */
  { tag: "КАРТА", re: /\b\d{4}[ -]?\d{4}[ -]?\d{4}[ -]?\d{4}\b/g },

  { tag: "СНИЛС", re: /\b\d{3}-\d{3}-\d{3}[ -]\d{2}\b/g },

  /* ОГРН 13 цифр, ОГРНИП 15. Раньше ИНН, иначе он съест начало. */
  { tag: "ОГРН", re: /\b\d{15}\b|\b\d{13}\b/g },

  /* ИНН 12 (физлицо, ИП) или 10 (организация) цифр.

     Ограничение слева и справа обязательно: без него правило
     выкусывало бы куски из длинных чисел и из сумм. */
  { tag: "ИНН", re: /\b\d{12}\b|\b\d{10}\b/g,
    skipNear: /(КБК|ОКТМО|ОКПО|ОКВЭД|БИК|УИН)[^\d]{0,20}$/i },

  /* Паспорт: серия и номер, обычно «12 34 567890» или слитно. */
  { tag: "ПАСПОРТ", re: /\b\d{2}\s?\d{2}\s?\d{6}\b/g },

  { tag: "ПОЧТА", re: /\b[\w.+-]+@[\w-]+\.[\w.-]{2,}\b/g },

  /* Телефон в любом из привычных видов. */
  { tag: "ТЕЛЕФОН", re: /(?:\+7|\b8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}\b/g },

  /* --- ФИО ---

     Три слова с заглавных букв подряд — «Иванов Иван Иванович».
     Отдельно фамилия с инициалами: «Иванов И. И.» и «И. И. Иванов».

     Русские отчества опознаются по окончанию: без этого правило
     ловило бы любые три слова с заглавной, включая «Налоговый Кодекс
     Российской». Это и есть главный источник ложных срабатываний,
     и лучше пропустить имя, чем испортить вопрос. */
  /* ВНИМАНИЕ про границы слова.

     Здесь нельзя писать \b: в JavaScript граница слова определяется
     через \w, а \w — это латиница, цифры и подчёркивание. Кириллица
     для движка не «словесный символ», поэтому \b перед «П» в
     «Петров П. П.» не находит границы, и правило не срабатывает
     вовсе — молча. Числовые правила выше при этом работают исправно,
     потому что цифры в \w входят, и со стороны маскирование выглядит
     живым. Имена не маскировались ни разу.

     Границы задаём явно, просмотром по кириллице.                  */
  { tag: "ФИО",
    re: /(?<![А-ЯЁа-яё])[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]*(?:ович|евич|ьич|овна|евна|ична)[а-яё]{0,3}(?![А-ЯЁа-яё])/g },

  /* «Иванов И. И.» и «И. И. Иванов» — обе формы встречаются в
     документах, и обе надо ловить. */
  { tag: "ФИО",
    re: /(?<![А-ЯЁа-яё])[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s?[А-ЯЁ]\./g },
  { tag: "ФИО",
    re: /(?<![А-ЯЁа-яё])[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?[А-ЯЁ][а-яё]+(?![А-ЯЁа-яё])/g },
];

/* Числа, которые похожи на опознаватели, но ими не являются.

   Ссылка на закон — «152-ФЗ», «44-ФЗ» — уже отсеивается дефисом, а
   вот год и суммы из десяти цифр теоретически могут совпасть с ИНН.
   Проверять контрольную сумму ИНН здесь не будем: маскировать лишнее
   безопаснее, чем пропустить настоящее. */
function looksLikeYear(v) {
  return /^(19|20)\d{2}$/.test(v);
}

/* Обезличить текст.

   Возвращает { text, map, count }: map нужен, чтобы вернуть настоящие
   значения в ответе модели. Он остаётся на нашем сервере и никуда
   не уходит. */
export function redact(text) {
  let out = String(text || "");
  const map = new Map();      // метка → исходное значение
  const seen = new Map();     // исходное значение → метка (одно значение — одна метка)
  const counters = {};

  for (const { tag, re, skipNear } of RULES) {
    out = out.replace(re, (hit, ...rest) => {
      const value = hit.trim();
      if (looksLikeYear(value)) return hit;

      /* Что написано перед числом. Последний аргумент replace — сама
         строка, предпоследний — позиция совпадения. */
      if (skipNear) {
        const at = rest[rest.length - 2];
        const whole = rest[rest.length - 1];
        if (skipNear.test(String(whole).slice(Math.max(0, at - 40), at))) return hit;
      }

      /* Одинаковые значения получают одну метку: иначе модель решит,
         что в договоре два разных человека с одинаковым ИНН. */
      if (seen.has(value)) return seen.get(value);

      counters[tag] = (counters[tag] || 0) + 1;
      const label = `[${tag}-${counters[tag]}]`;
      seen.set(value, label);
      map.set(label, value);
      return label;
    });
  }

  return { text: out, map, count: map.size };
}

/* Вернуть настоящие значения в ответ модели.

   Без этого человек получил бы «[ФИО-1] обязан уплатить» и решил бы,
   что сервис сломался. */
export function restore(text, map) {
  let out = String(text || "");
  for (const [label, value] of map) {
    /* Метки в квадратных скобках — экранируем, иначе они попадут в
       регулярное выражение как группа символов. */
    out = out.split(label).join(value);
  }
  return out;
}

/* Обезличивание включено? Выключатель есть намеренно: если правило
   однажды начнёт портить вопросы, отключить его надо мгновенно, без
   выкатки кода. По умолчанию включено — молчаливое отсутствие защиты
   хуже, чем молчаливое её наличие. */
export function redactOn(env) {
  return String(env.REDACT_PII ?? "1") !== "0";
}
