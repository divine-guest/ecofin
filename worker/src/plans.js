/* Сколько «подарочных» месяцев даёт годовая оплата. Человек понимает
   «два месяца в подарок» мгновенно, а «34%» — нет. */
export function freeMonths(id) {
  const p = PLANS[id];
  if (!p || !p.price.month) return 0;
  return Math.round((p.price.month * 12 - p.price.year) / p.price.month);
}

