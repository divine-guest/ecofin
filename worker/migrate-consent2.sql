-- Дата согласия: из миллисекунд в читаемый вид.
--
-- Колонка consent_at заведена как TEXT, а первые несколько часов в неё
-- писалось число миллисекунд. SQLite привёл его к тексту через REAL, и
-- в базе осело «1788835546043.0» — значение, которое не совпадало с
-- тем, что сервер возвращал в ответе.
--
-- Дата согласия — доказательство, и его читают люди. Поэтому приводим
-- к ISO-8601: он и сортируется как текст, и понятен без пересчёта.
--
-- GLOB '[0-9]*' отбирает только числовые значения: строки, уже
-- записанные в новом виде, начинаются с года и тоже попали бы под
-- LIKE-проверку, а под эту — нет, потому что дальше идёт дефис.
UPDATE users
   SET consent_at = strftime('%Y-%m-%dT%H:%M:%SZ',
                             CAST(consent_at AS INTEGER) / 1000, 'unixepoch')
 WHERE consent_at IS NOT NULL
   AND consent_at NOT LIKE '%-%'
   AND consent_at GLOB '[0-9]*';
