-- Письма на почту: напоминания о сроках, сводка недели, предупреждение
-- перед автопродлением.
-- Запускается один раз; повторный запуск вернёт «duplicate column» — это нормально.
--
-- mail_off — человек отключил письма. Отдельным полем, а не удалением
-- чего-либо: настройку нужно помнить, и отключают её двумя путями —
-- галкой в кабинете и ссылкой из письма, без входа.
--
-- mail_token — ключ этой ссылки. Случайная строка, а не адрес почты:
-- адрес в ссылке попал бы в журналы почтовых сервисов и веб-сервера.
-- Ключом можно только отключить и включить письма, войти по нему нельзя.
--
-- renew_notice — конец оплаченного срока, о продлении которого человека
-- уже предупредили. Без отметки предупреждение приходило бы каждый час;
-- после продления срок меняется, и следующее предупреждение уйдёт само.

ALTER TABLE users ADD COLUMN mail_off INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN mail_token TEXT DEFAULT '';
ALTER TABLE users ADD COLUMN renew_notice INTEGER;

CREATE INDEX IF NOT EXISTS idx_users_mail_token ON users(mail_token);
