#!/bin/bash
# ============ Прогнать проверки прямо на сервере ============
#
# Зачем так странно. Сюиты из tests/ делают две вещи одновременно: бьют
# по серверу запросами и лезут в базу напрямую — чтобы завести одноразовый
# аккаунт и повысить его до админа. Значит запускать их надо там, где есть
# и сервер, и файл базы. Это сама машина.
#
# А зайти на неё нельзя: yc compute ssh отказывает, OS Login не работает.
# Поэтому машина запускает проверки сама и выкладывает результат на сайт —
# единственный канал, по которому с неё можно что-то прочитать.
#
# Запускается из setup.sh, когда в репозитории меняется файл RUN-TESTS.
# То есть «запустить проверки» — это обычная выкладка, как и всё остальное.

set -uo pipefail

DIR=/opt/pravofin
REPO=$DIR/repo
OUT=$REPO/tests-8f3a2c.txt
DB=$DIR/data/pravofin.db

{
  echo "Проверки ПравоФина"
  echo "запущены: $(date -Is)"
  echo "версия кода: $(git -C "$REPO" rev-parse --short HEAD 2>/dev/null || cat "$REPO/.version" 2>/dev/null | cut -c1-12)"
  echo

  if ! curl -fsS -m 10 http://127.0.0.1:8080/api/health >/dev/null 2>&1; then
    echo "СЕРВИС НЕ ОТВЕЧАЕТ — проверять нечего."
    exit 0
  fi

  echo "=== начало ==="
  # Обращаемся к серверу по внутреннему адресу: так проверяется именно он,
  # а не дорога до него. Доступность снаружи — отдельная забота, ею
  # занимается watch-outside.sh.
  cd "$REPO" && API_URL=http://127.0.0.1:8080 DB_FILE="$DB" \
    timeout 900 node tests/run-all.mjs 2>&1
  echo "=== конец, код возврата: $? ==="
} > "$OUT" 2>&1

chmod 644 "$OUT"
chown pravofin:pravofin "$OUT" 2>/dev/null || true
