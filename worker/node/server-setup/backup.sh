#   openssl enc -d -aes-256-cbc -pbkdf2 -iter 100000 \
#     -in pravofin-ГГГГММДД-ЧЧММ.db.gz.enc -out копия.db.gz -pass pass:КЛЮЧ
#   gunzip копия.db.gz
