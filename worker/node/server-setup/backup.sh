#!/bin/bash
# Почасовая копия базы.
#
# VACUUM INTO делает целостную копию на работающей базе, в отличие от
# обычного копирования файла: при копировании можно поймать середину
# записи и получить битый файл.
set -e
DIR=/opt/pravofin/backups
mkdir -p "$DIR"
chmod 700 "$DIR"
STAMP=$(date +%Y%m%d-%H%M)
sqlite3 /opt/pravofin/data/pravofin.db "VACUUM INTO '$DIR/pravofin-$STAMP.db'"
gzip -f "$DIR/pravofin-$STAMP.db"
chmod 600 "$DIR/pravofin-$STAMP.db.gz"

# Шифруем копию.
#
# В копии — всё: учётные записи, учёт доходов, документы с реквизитами
# контрагентов, история обращений. Лежит она на той же машине, что и
# рабочая база, поэтому один доступ к серверу означал утечку не только
# текущего состояния, но и истории за двое суток.
#
# Ключ берём из worker/.env — он и так нужен серверу и в репозиторий
# не попадает. Без ключа копия бесполезна тому, кто унёс диск.
#
# Ключа нет — копия остаётся незашифрованной, но в журнал пишется
# предупреждение. Останавливать резервное копирование из-за
# отсутствия ключа нельзя: без копий потеря данных гарантирована,
# а без шифрования — только возможна.
# Ключ: сначала из .env, иначе из отдельного файла, который заводится
# при настройке машины. Второй путь нужен, чтобы шифрование работало
# без единого действия владельца.
#
# ЧЕСТНО ПРО ПРЕДЕЛ ЗАЩИТЫ. Ключ лежит на той же машине, что и копии.
# Это защищает от кражи диска, снимка диска и от выноса самих копий
# наружу — но не от того, кто получил доступ к серверу: он возьмёт и
# копии, и ключ. Настоящая защита от второго случая — выгружать копии
# в отдельное хранилище с ключом, которого на сервере нет.
KEY=$(grep -m1 '^BACKUP_KEY=' /opt/pravofin/repo/worker/.env 2>/dev/null | cut -d= -f2-)
[ -z "$KEY" ] && [ -r /opt/pravofin/backup.key ] && KEY=$(cat /opt/pravofin/backup.key)
if [ -n "$KEY" ]; then
  if openssl enc -aes-256-cbc -pbkdf2 -iter 100000 -salt \
       -in "$DIR/pravofin-$STAMP.db.gz" \
       -out "$DIR/pravofin-$STAMP.db.gz.enc" -pass "pass:$KEY" 2>/dev/null; then
    shred -u "$DIR/pravofin-$STAMP.db.gz" 2>/dev/null || rm -f "$DIR/pravofin-$STAMP.db.gz"
    chmod 600 "$DIR/pravofin-$STAMP.db.gz.enc"
  else
    echo "backup: не удалось зашифровать копию, оставлена открытой"
  fi
else
  echo "backup: BACKUP_KEY не задан — копия сохранена без шифрования"
fi

# ---------------------------------------------------------------------
# Копия за пределы сервера
#
# Всё, что выше, лежит на той же машине, что и рабочая база. От кражи
# диска это защищает, от человека, получившего доступ к серверу, — нет:
# он возьмёт и копии, и ключ. И от потери самой машины тоже не спасает.
#
# Поэтому раз в сутки зашифрованная копия уезжает в отдельное хранилище.
#
# Отправляем ТОЛЬКО зашифрованную копию. Если шифрование не удалось,
# наружу не уходит ничего: отправить открытую базу в чужое хранилище
# было бы хуже, чем не иметь внешней копии вовсе.
#
# curl умеет подписывать запросы по правилам S3 сам (--aws-sigv4), так
# что ставить на машину ничего не нужно. Подходит любое S3-совместимое
# хранилище; ниже настроено под Yandex Object Storage.
#
# Переменные в worker/.env:
#   BACKUP_S3_URL     https://storage.yandexcloud.net/имя-бакета
#   BACKUP_S3_KEY     идентификатор статического ключа
#   BACKUP_S3_SECRET  сам ключ
#   BACKUP_S3_REGION  по умолчанию ru-central1
#
# ВАЖНО: ключ шифрования копий (BACKUP_KEY) в это хранилище класть
# нельзя ни при каких обстоятельствах. Смысл внешней копии в том, что
# укравший её не может её прочитать. Ключ хранится отдельно — например,
# в менеджере паролей владельца.
#
# И ещё: у бакета должно стоять правило удаления старых объектов
# (30 дней достаточно) и запрет публичного доступа. Хранилище, которое
# растёт бесконечно и открыто наружу, — это не резервная копия, а
# вторая утечка.
ENC="$DIR/pravofin-$STAMP.db.gz.enc"
HOUR=$(date +%H)
ENVF=/opt/pravofin/repo/worker/.env
getenv() { grep -m1 "^$1=" "$ENVF" 2>/dev/null | cut -d= -f2-; }

if [ -f "$ENC" ] && [ "$HOUR" = "04" ]; then
  S3URL=$(getenv BACKUP_S3_URL)
  S3KEY=$(getenv BACKUP_S3_KEY)
  S3SEC=$(getenv BACKUP_S3_SECRET)
  S3REG=$(getenv BACKUP_S3_REGION); [ -z "$S3REG" ] && S3REG=ru-central1

  if [ -n "$S3URL" ] && [ -n "$S3KEY" ] && [ -n "$S3SEC" ]; then
    DAY=$(date +%Y%m%d)
    DEST="${S3URL%/}/pravofin-$DAY.db.gz.enc"
    ARGS=(-sS -f --max-time 300)
    ARGS+=(--aws-sigv4 "aws:amz:$S3REG:s3")
    ARGS+=(--user "$S3KEY:$S3SEC")
    ARGS+=(-H "Content-Type: application/octet-stream")
    ARGS+=(-T "$ENC")
    if curl "${ARGS[@]}" "$DEST" >/dev/null; then
      echo "backup: копия за $DAY отправлена в хранилище"
      date -Iseconds > /opt/pravofin/backups/.last-offsite
    else
      # Не молчим: внешняя копия, которая перестала уезжать, обычно
      # обнаруживается ровно тогда, когда она нужна.
      echo "backup: НЕ УДАЛОСЬ отправить копию в хранилище — проверьте ключи и бакет"
    fi
  fi
fi

# Держим двое суток почасовых копий. Оба вида имён: во время перехода
# на шифрование в папке лежат и старые открытые копии, и новые.
ls -1t "$DIR"/pravofin-*.db.gz.enc 2>/dev/null | tail -n +49 | xargs -r rm --
ls -1t "$DIR"/pravofin-*.db.gz 2>/dev/null | tail -n +49 | xargs -r rm --

