#!/bin/bash
# ============ Закрепить нынешний адрес за собой ============
#
# Адрес, который машина получила при перезапуске, — временный. Стоит ей
# однажды выключиться, и он уйдёт другому, а машина получит новый. После
# того, как мы перебирали адреса в поисках такого, который вообще виден
# снаружи, потерять рабочий было бы обидно вдвойне: следующий с большой
# вероятностью окажется таким же непригодным.
#
# Скрипт делает ровно одно: закрепляет тот адрес, который у машины сейчас.
# Ничего не удаляет, ничего не переставляет, машину не трогает — меняется
# только статус адреса, из временного в постоянный. Сам адрес остаётся
# тем же самым, так что сайт в этот момент не моргнёт.
#
# Запускать в Cloud Shell:
#   curl -fsSL https://raw.githubusercontent.com/divine-guest/ecofin/main/worker/node/keep-ip.sh -o keep.sh
#   bash keep.sh

set -uo pipefail

NAME="${VM_NAME:-pravofin}"
ADDR_NAME="${ADDR_NAME:-pravofin-ip}"

say()  { printf '%s\n' "$*"; }
fail() { printf '\n  ОШИБКА: %s\n\n' "$*" >&2; exit 1; }
field() { awk -F': *' -v k="$1" '$0 ~ "^ *" k ":" { print $2; exit }'; }

say ""
say "=== Закрепляю адрес ==="
say ""

command -v yc >/dev/null 2>&1 || fail "не нашёл команду yc — запускать нужно в Cloud Shell"

INFO=$(yc compute instance get --name "$NAME" 2>&1)
printf '%s' "$INFO" | grep -q 'status:' || fail "не нашёл машину «$NAME»:
$INFO"

ZONE=$(printf '%s\n' "$INFO" | field zone_id)
IP=$(printf '%s\n' "$INFO" | awk '/one_to_one_nat/,0' | field address)
[ -n "$IP" ]   || fail "у машины нет публичного адреса"
[ -n "$ZONE" ] || fail "не понял, в какой зоне машина"

say "  машина  $NAME"
say "  зона    $ZONE"
say "  адрес   $IP"
say ""

# Адрес можно назвать и явно:  bash keep.sh 51.250.107.176
#
# Вписывать его в сам скрипт нельзя: адрес меняется, и вписанный однажды
# после любой смены закреплял бы чужой. Поэтому берём у машины, а если
# адрес назвали руками — сверяем. Расхождение почти всегда значит, что
# смотрят на старую вкладку браузера.
WANT="${1:-}"
if [ -n "$WANT" ] && [ "$WANT" != "$IP" ]; then
  fail "вы назвали адрес $WANT, а у машины сейчас $IP.

  Закреплять нужно тот, что у машины. Если $WANT — это то, что открыто
  в браузере, обновите страницу: адрес мог смениться.
  Если уверены, что права машина, — запустите без адреса:  bash keep.sh"
fi

# Уже закреплён — второй раз не надо, да и не выйдет.
if yc vpc address list 2>/dev/null | grep -q "$IP"; then
  say "Этот адрес уже закреплён, делать нечего."
  say ""
  exit 0
fi

# Имя может быть занято прошлым адресом. Тогда берём соседнее, вместо
# того чтобы останавливать человека из-за такой мелочи.
if yc vpc address get --name "$ADDR_NAME" >/dev/null 2>&1; then
  ADDR_NAME="$ADDR_NAME-$(date +%m%d)"
  say "Имя pravofin-ip занято, беру $ADDR_NAME"
fi

say "Закрепляю $IP…"
ERR=$(yc vpc address create --name "$ADDR_NAME" \
        --external-ipv4 "address=$IP,zone=$ZONE" 2>&1) \
  || fail "не смог закрепить адрес:
$(printf '%s' "$ERR" | head -4)

  То же самое в консоли: Compute Cloud → $NAME → раздел «Сеть» →
  у публичного адреса выбрать «Сделать статическим»."

say ""
say "=== Готово ==="
say ""
say "  Адрес $IP закреплён под именем $ADDR_NAME."
say "  При перезапуске машины он больше не изменится,"
say "  и на него же будет указывать домен, когда вы его купите."
say ""
